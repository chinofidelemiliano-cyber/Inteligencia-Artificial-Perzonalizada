    await page.getByRole('button',{name:'Preparar entregable en Agenda'}).click();
    assert.equal(await page.locator('#taskTitle').inputValue(),'entregar el informe');
    assert.equal(await page.locator('#taskDate').inputValue(),'2099-12-09');
    assert.equal(await page.locator('#taskSteps').inputValue(),'Medir una muestra\nRevisar el informe');
    assert.equal(await page.evaluate(()=>window.liftsWorkspace.getState().tasks.length),1);
