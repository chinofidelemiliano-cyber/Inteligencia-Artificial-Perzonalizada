    await page.getByText('Seguimiento guardado.',{exact:true}).waitFor();
    await page.getByText(/Programado para 2000-01-02/).waitFor();
    const catalog=page.locator('#guardianRecords article').filter({has:page.getByRole('heading',{name:'Recuperar catálogo',exact:true})});
    await catalog.getByRole('button',{name:'Preparar recordatorio',exact:true}).click();
